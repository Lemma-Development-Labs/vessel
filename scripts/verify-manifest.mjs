#!/usr/bin/env node
/**
 * Writes app/lib/verification.ts — the per-contract source-verification state
 * the Transparency screen renders.
 *
 * The app used to badge all 11 contracts "VERIFIED" when only DemoUSD's
 * Sourcify verification had ever been confirmed. The fix is that the badge
 * reads state, and the state comes from here: a contract is "verified" only
 * when a verification run says so and hands us the timestamp to prove it.
 * Anything we have not checked is "unknown" and renders dim.
 *
 * Usage:
 *   node scripts/verify-manifest.mjs                       # reset every contract to unknown
 *   node scripts/verify-manifest.mjs --results r.json      # apply a verification run's results
 *   node scripts/verify-manifest.mjs --verified DemoUSD    # mark one contract, checkedAt = now
 *
 * The results file is `{ "<Contract>": <state> }` or, with evidence:
 *   { "DemoUSD": { "state": "verified", "checkedAt": "2026-08-29T10:00:00Z", "url": "https://…" } }
 * A contract in ADDRESSES.json with no result is emitted as unknown/null, so a
 * redeploy that nobody re-verified can never inherit the old deploy's badge.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const STATES = ["verified", "unverified", "unknown"];

const args = process.argv.slice(2);
let resultsPath = null;
const cli = {};
for (let i = 0; i < args.length; i++) {
  if (args[i] === "--results") resultsPath = args[++i];
  else if (args[i] === "--verified") cli[args[++i]] = "verified";
  else if (args[i] === "--unverified") cli[args[++i]] = "unverified";
  else {
    console.error("unknown argument", args[i]);
    process.exit(1);
  }
}

const addressesPath = join(root, "ADDRESSES.json");
if (!existsSync(addressesPath)) {
  console.error("missing ADDRESSES.json — deploy first");
  process.exit(1);
}
const addresses = JSON.parse(readFileSync(addressesPath, "utf8"));
const names = Object.keys(addresses.contracts).sort();

let results = {};
if (resultsPath) {
  if (!existsSync(resultsPath)) {
    console.error("missing results file", resultsPath);
    process.exit(1);
  }
  results = JSON.parse(readFileSync(resultsPath, "utf8"));
}
for (const [name, state] of Object.entries(cli)) results[name] = state;

const now = new Date().toISOString();
const unknown = { state: "unknown", checkedAt: null };

const entries = {};
for (const name of names) {
  const raw = results[name];
  if (raw === undefined) {
    entries[name] = unknown;
    continue;
  }
  const r = typeof raw === "string" ? { state: raw } : raw;
  if (!STATES.includes(r.state)) {
    console.error(`bad state for ${name}: ${JSON.stringify(r.state)} — expected one of ${STATES.join(", ")}`);
    process.exit(1);
  }
  // "verified" without a timestamp is exactly the unfalsifiable claim this
  // manifest exists to stop, so it never lands in the file.
  const checkedAt = r.state === "unknown" ? null : (r.checkedAt ?? now);
  entries[name] = r.url ? { state: r.state, checkedAt, url: r.url } : { state: r.state, checkedAt };
}

for (const name of Object.keys(results)) {
  if (!names.includes(name)) {
    console.error(`result for ${name}, which is not in ADDRESSES.json`);
    process.exit(1);
  }
}

const fields = (e) =>
  Object.entries(e)
    .map(([k, v]) => `${k}: ${JSON.stringify(v)}`)
    .join(", ");

const body = names
  .map((name) => `  ${JSON.stringify(name)}: { ${fields(entries[name])} },`)
  .join("\n");

const ts = `// Generated by \`pnpm verify:manifest\` (scripts/verify-manifest.mjs) — do not edit by hand.
//
// Per-contract source-verification state for the Transparency screen. A row
// renders the VERIFIED badge only where state is "verified"; everything else
// renders a dim, explicit label. Every contract is seeded "unknown" because
// nothing has been re-verified against the coming redeploy — hand-editing a
// state here would put the old false claim straight back on the page.
//
// Regenerate after a verification run:
//   pnpm verify:manifest --results <results.json>

export type VerificationState = "verified" | "unverified" | "unknown";

export type VerificationEntry = {
  state: VerificationState;
  /** ISO-8601 instant the state was established, or null if never checked. */
  checkedAt: string | null;
  /** Link to the verification evidence, when the run produced one. */
  url?: string;
};

export const VERIFICATION: Record<string, VerificationEntry> = {
${body}
};

/** Unknown is the safe default: a name with no entry is never shown as verified. */
export function verificationOf(name: string): VerificationEntry {
  return VERIFICATION[name] ?? { state: "unknown", checkedAt: null };
}
`;

const outPath = join(root, "app/lib/verification.ts");
writeFileSync(outPath, ts);
const counts = STATES.map((s) => `${s}=${names.filter((n) => entries[n].state === s).length}`);
console.log(`wrote app/lib/verification.ts — ${names.length} contracts (${counts.join(" ")})`);
