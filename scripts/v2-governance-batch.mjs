#!/usr/bin/env node
/**
 * Turn a governance batch spec into two Safe Transaction Builder files: one that
 * schedules the batch on the v2 TimelockController and one that executes it
 * after the delay. The Safe (2-of-3) signs each; nothing here holds a key or
 * sends a transaction.
 *
 *   node scripts/v2-governance-batch.mjs <spec.json> [manifest.json]
 *
 * spec.json: { "name": "...", "salt": "<unique string>", "calls": [
 *   { "to": "TrancheController", "sig": "setStageCap(uint256)", "args": ["1000000000"] }, ... ] }
 * `to` and any arg of the form "@Name" resolve from the manifest's contracts
 * (or roles). Encoding uses Foundry's `cast calldata`, and each call is decoded
 * back with `cast calldata-decode` as a check.
 *
 * Output: <spec>.schedule.safe.json and <spec>.execute.safe.json next to the spec.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";

const [specPath, manifestPath = "deployments/testnet-v2.json"] = process.argv.slice(2);
if (!specPath) {
  console.error("usage: node scripts/v2-governance-batch.mjs <spec.json> [manifest.json]");
  process.exit(2);
}
const spec = JSON.parse(readFileSync(specPath, "utf8"));
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
const book = { ...manifest.contracts, ...(manifest.roles ?? {}) };

const resolve = (v) => {
  if (typeof v !== "string") return String(v);
  if (v.startsWith("@")) {
    const addr = book[v.slice(1)];
    if (!addr) throw new Error(`unknown manifest name ${v}`);
    return addr;
  }
  return v;
};
const cast = (...args) => execFileSync("cast", args, { encoding: "utf8" }).trim();

const timelock = book.TimelockController;
if (!timelock) throw new Error("manifest has no TimelockController");
const delay = String(manifest.timelockDelaySeconds);

const targets = [];
const payloads = [];
for (const call of spec.calls) {
  const to = resolve(call.to.startsWith("@") ? call.to : `@${call.to}`);
  const args = (call.args ?? []).map(resolve);
  const calldata = cast("calldata", call.sig, ...args);
  cast("calldata-decode", call.sig, calldata); // round-trip check: throws if malformed
  targets.push(to);
  payloads.push(calldata);
  console.log(`  ${call.sig.padEnd(34)} -> ${to}`);
}
const values = targets.map(() => "0");
const salt = "0x" + createHash("sha256").update(`vessel-v2:${spec.salt}`).digest("hex");
const predecessor = "0x" + "00".repeat(32);
const arr = (xs) => `[${xs.join(",")}]`;

const scheduleData = cast(
  "calldata",
  "scheduleBatch(address[],uint256[],bytes[],bytes32,bytes32,uint256)",
  arr(targets), arr(values), arr(payloads), predecessor, salt, delay,
);
const executeData = cast(
  "calldata",
  "executeBatch(address[],uint256[],bytes[],bytes32,bytes32)",
  arr(targets), arr(values), arr(payloads), predecessor, salt,
);

const safeFile = (label, data) => ({
  version: "1.0",
  chainId: String(manifest.chainId),
  createdAt: Date.now(),
  meta: {
    name: `${spec.name} — ${label}`,
    description: `${label} of ${spec.calls.length} timelocked calls (delay ${delay}s, salt ${spec.salt}). Generated by scripts/v2-governance-batch.mjs.`,
  },
  transactions: [{ to: timelock, value: "0", data }],
});

const base = join(dirname(specPath), basename(specPath, ".json"));
writeFileSync(`${base}.schedule.safe.json`, JSON.stringify(safeFile("schedule", scheduleData), null, 2) + "\n");
writeFileSync(`${base}.execute.safe.json`, JSON.stringify(safeFile("execute", executeData), null, 2) + "\n");
console.log(`wrote ${base}.schedule.safe.json and ${base}.execute.safe.json`);
console.log(`operation id: ${cast("keccak", cast("abi-encode", "f(address[],uint256[],bytes[],bytes32,bytes32)", arr(targets), arr(values), arr(payloads), predecessor, salt))}`);
