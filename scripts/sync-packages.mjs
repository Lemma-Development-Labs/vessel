#!/usr/bin/env node
/**
 * Vendors shared packages into consumers that deploy standalone
 * (docs/ARCHITECTURE.md decision 1: vessel-service builds on Railway from its
 * own directory, so it cannot reach ../packages at build time).
 *
 *   node scripts/sync-packages.mjs          write the vendored copies
 *   node scripts/sync-packages.mjs --check  exit 1 if any copy has drifted (CI)
 *
 * The copy is byte-for-byte the source plus a generated header naming the
 * source file and its SHA-256. Never edit a vendored file; edit the package
 * and re-run this script.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const TARGETS = [
  {
    source: "packages/config/src/index.ts",
    dest: "vessel-service/src/vendor/vessel-config.ts",
  },
  // The /v1 API reads the book with the independent verifier's own code, so the
  // API and `vessel-verify` cannot silently disagree about what they check.
  {
    source: "tools/verify-cli/src/checks.ts",
    dest: "vessel-service/src/vendor/verify/checks.ts",
  },
  {
    source: "tools/verify-cli/src/read.ts",
    dest: "vessel-service/src/vendor/verify/read.ts",
  },
];

function render(sourcePath) {
  const body = readFileSync(join(root, sourcePath), "utf8");
  const sha = createHash("sha256").update(body).digest("hex");
  return (
    `// GENERATED by scripts/sync-packages.mjs from ${sourcePath}\n` +
    `// source sha256 ${sha} — do not edit; edit the package and re-run the script.\n\n` +
    body
  );
}

const check = process.argv.includes("--check");
let drift = 0;

for (const { source, dest } of TARGETS) {
  const want = render(source);
  const destPath = join(root, dest);
  const have = existsSync(destPath) ? readFileSync(destPath, "utf8") : null;
  if (have === want) {
    console.log(`ok       ${dest}`);
    continue;
  }
  if (check) {
    console.error(`DRIFT    ${dest} is not the generated copy of ${source} — run node scripts/sync-packages.mjs`);
    drift++;
    continue;
  }
  mkdirSync(dirname(destPath), { recursive: true });
  writeFileSync(destPath, want);
  console.log(`wrote    ${relative(root, destPath)}`);
}

if (drift > 0) process.exit(1);
